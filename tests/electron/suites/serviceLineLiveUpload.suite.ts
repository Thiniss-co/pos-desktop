const UPLOAD_PATH = '/api/v1/desktop/invoices/upload'

/**
 * PS8 — a v3 invoice carrying an **untracked service line**, generated by the desktop's own payload
 * builder and accepted by a real Laravel over real HTTP.
 *
 * This is the `POS-235a06-20260914-000003` incident executed rather than described. The body is not
 * hand-written here and not minted by the backend seeder: it comes out of `buildUploadPayload()`,
 * the same function the upload worker calls on committed rows, so what is proven is that real
 * Electron output is accepted — which a hand-authored body could never establish.
 *
 * Skips when no live backend was provided, so `npm run test:sqlite:electron` stays hermetic.
 */
function liveTest(name: string, callback: () => Promise<void>): void {
  databaseTest(name, async () => await callback(), {
    skip: liveServiceLineBackendAvailable() ? false : 'no live PS8 service-line backend provided'
  })
}

async function upload(body: Record<string, unknown>): Promise<Response> {
  const fixture = liveUploadFixture()
  ok(fixture !== null)

  return fetch(new URL(UPLOAD_PATH, fixture.origin), {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${fixture.token}`,
      'X-Device-UUID': fixture.deviceUuid,
      'Content-Type': 'application/json',
      Accept: 'application/json'
    },
    body: JSON.stringify(body)
  })
}

