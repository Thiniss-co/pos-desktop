liveTest(
  'PS8 a desktop-generated v3 service-line payload is accepted by real Laravel and moves no stock',
  async () => {
    const fixture = liveUploadFixture()
    ok(fixture !== null)

    const context = fixture.serviceLineContext
    ok(context !== null)

    const localUuid = randomUUID()
    const amount = context.service.unit_price_amount
    const payload = buildUploadPayload(
      committedInvoice(context, localUuid, amount),
      [
        committedItem(context.service, localUuid, {
          lineIndex: 0,
          trackStock: false,
          quantityMilli: 1_000,
          currency: context.currency
        })
      ],
      [committedPayment(context, localUuid, amount)],
      new Map(),
      new Map()
    )

    // The generator's own output is the incident's shape: v3, and a line carrying NEITHER key.
    equal(payload.client_contract_version, 3)
    const line = (payload.items as Record<string, unknown>[])[0]
    equal(Object.prototype.hasOwnProperty.call(line, 'stock_authorization'), false)
    equal(Object.prototype.hasOwnProperty.call(line, 'allocations'), false)

    const response = await upload(payload)

    equal(response.status, 201)

    const offlineNumber = payload.offline_number as string

    equal(
      serverScalar(
        'SELECT COUNT(*) AS total FROM pos_invoices WHERE offline_number = ?',
        offlineNumber
      ),
      1
    )
    // A service touches no ledger: no movement, no consumption, and no stock item conjured for it.
    equal(
      serverScalar(
        `SELECT COUNT(*) AS total FROM stock_movements m
           JOIN pos_invoices i ON i.id = m.pos_invoice_id
          WHERE i.offline_number = ?`,
        offlineNumber
      ),
      0
    )
    equal(
      serverScalar(
        'SELECT COUNT(*) AS total FROM stock_allocation_consumptions WHERE invoice_idempotency_key = ?',
        localUuid
      ),
      0
    )
    equal(
      serverScalar(
        `SELECT COUNT(*) AS total FROM stock_items s
           JOIN products p ON p.id = s.product_id
          WHERE p.uuid = ?`,
        context.service.product_uuid
      ),
      0
    )
  }
)

liveTest('PS8 an exact replay of the service sale writes nothing further', async () => {
  // The recovery case: the same frozen bytes, re-offered under the same idempotency key, resolve to
  // the committed invoice instead of creating a second one.
  const fixture = liveUploadFixture()
  ok(fixture !== null)

  const context = fixture.serviceLineContext
  ok(context !== null)

  const localUuid = randomUUID()
  const amount = context.service.unit_price_amount
  const payload = buildUploadPayload(
    committedInvoice(context, localUuid, amount),
    [
      committedItem(context.service, localUuid, {
        lineIndex: 0,
        trackStock: false,
        quantityMilli: 1_000,
        currency: context.currency
      })
    ],
    [committedPayment(context, localUuid, amount)],
    new Map(),
    new Map()
  )

  equal((await upload(payload)).status, 201)

  const invoicesBefore = serverScalar('SELECT COUNT(*) AS total FROM pos_invoices')
  const paymentsBefore = serverScalar('SELECT COUNT(*) AS total FROM pos_payments')
  const movementsBefore = serverScalar('SELECT COUNT(*) AS total FROM stock_movements')

  // 200 duplicate, not 201.
  equal((await upload(payload)).status, 200)

  equal(serverScalar('SELECT COUNT(*) AS total FROM pos_invoices'), invoicesBefore)
  equal(serverScalar('SELECT COUNT(*) AS total FROM pos_payments'), paymentsBefore)
  equal(serverScalar('SELECT COUNT(*) AS total FROM stock_movements'), movementsBefore)
  equal(
    serverScalar(
      'SELECT COUNT(*) AS total FROM desktop_invoice_syncs WHERE local_invoice_uuid = ?',
      localUuid
    ),
    1
  )
})

liveTest(
  'PS8 a mixed tracked/untracked v3 payload settles each line on its own terms',
  async () => {
    const fixture = liveUploadFixture()
    ok(fixture !== null)

    const context = fixture.serviceLineContext
    ok(context !== null)

    const localUuid = randomUUID()
    const amount = context.tracked.unit_price_amount + context.service.unit_price_amount
    const payload = buildUploadPayload(
      committedInvoice(context, localUuid, amount),
      [
        // Tracked, held no grant: a genuine physical-presence deduction, declared as such.
        committedItem(context.tracked, localUuid, {
          lineIndex: 0,
          trackStock: true,
          quantityMilli: 1_000,
          currency: context.currency
        }),
        committedItem(context.service, localUuid, {
          lineIndex: 1,
          trackStock: false,
          quantityMilli: 1_000,
          currency: context.currency
        })
      ],
      [committedPayment(context, localUuid, amount)],
      new Map(),
      new Map()
    )

    const items = payload.items as Record<string, unknown>[]

    equal(items[0].stock_authorization, 'physical_presence')
    equal(Object.prototype.hasOwnProperty.call(items[1], 'stock_authorization'), false)

    equal((await upload(payload)).status, 201)

    const offlineNumber = payload.offline_number as string

    // Exactly one movement for the two-line invoice, and it belongs to the tracked product.
    equal(
      serverScalar(
        `SELECT COUNT(*) AS total FROM stock_movements m
         JOIN pos_invoices i ON i.id = m.pos_invoice_id
        WHERE i.offline_number = ?`,
        offlineNumber
      ),
      1
    )
    equal(
      serverScalar(
        `SELECT COUNT(*) AS total FROM stock_movements m
         JOIN pos_invoices i ON i.id = m.pos_invoice_id
         JOIN products p ON p.id = m.product_id
        WHERE i.offline_number = ? AND p.uuid = ? AND m.stock_authorization = 'physical_presence'`,
        offlineNumber,
        context.tracked.product_uuid
      ),
      1
    )
    equal(
      serverScalar(
        `SELECT COUNT(*) AS total FROM pos_invoice_items it
         JOIN pos_invoices i ON i.id = it.pos_invoice_id
        WHERE i.offline_number = ?`,
        offlineNumber
      ),
      2
    )
  }
)
