function committedItem(
  entry: ServiceLineCatalogEntry,
  invoiceLocalUuid: string,
  options: {
    readonly lineIndex: number
    readonly trackStock: boolean
    readonly quantityMilli: number
    readonly currency: string
    readonly coveredMilli?: number
  }
): LocalInvoiceItemRow {
  const total = (entry.unit_price_amount * options.quantityMilli) / 1000
  const covered = options.coveredMilli ?? 0

  return {
    localUuid: randomUUID(),
    invoiceLocalUuid,
    lineIndex: options.lineIndex,
    productUuid: entry.product_uuid,
    productName: options.trackStock ? 'Tracked Item' : 'Service Item',
    sku: options.trackStock ? null : 'PS-SERVICE',
    barcode: options.trackStock ? null : '2000000000039',
    unit: null,
    trackStock: options.trackStock,
    quantityMilli: options.quantityMilli,
    unitPriceAmount: entry.unit_price_amount,
    currency: options.currency,
    priceRevision: entry.price_revision,
    taxUuid: entry.tax_id,
    taxMode: 'none',
    taxRateBasisPoints: entry.tax_rate_basis_points,
    taxRevision: entry.tax_revision,
    discountType: null,
    discountValue: 0,
    subtotalAmount: total,
    discountAmount: 0,
    taxAmount: 0,
    totalAmount: total,
    allocationCoveredMilli: options.trackStock ? covered : 0,
    uncoveredMilli: options.trackStock ? options.quantityMilli - covered : 0,
    createdAt: '2026-09-14T12:32:04.733Z'
  }
}

